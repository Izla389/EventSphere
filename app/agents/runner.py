
from sqlalchemy.orm import Session

from app.agents.venue_agent import process_venue_requests
from app.agents.booking_agent import process_booking_requests
from app.agents.ticket_agent import process_ticket_requests
from app.agents.waitlist_agent import process_waitlist_requests
from app.agents.notification_agent import process_notifications


def run_agents(db: Session):
    """
    Process agent messages in multiple rounds.

    Multiple rounds allow messages generated by one
    agent to reach another agent during the same run.
    """

    results = []

    processors = [
        process_venue_requests,
        process_booking_requests,
        process_ticket_requests,
        process_waitlist_requests,
        process_notifications,
    ]

    for _ in range(3):
        round_processed = 0

        for processor in processors:
            result = processor(db)

            results.append(result)
            round_processed += result.get("processed", 0)

        if round_processed == 0:
            break

    return results
